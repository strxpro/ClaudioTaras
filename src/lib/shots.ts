import fs from "node:fs";
import path from "node:path";
import type { Project } from "./types";

export type Shots = { desktop: string[]; mobile: string[]; extra: string[]; pages: string[]; clips: string[]; logo: { src: string; tone: "light" | "dark" | "box" } | null };

const ROOT = path.join(process.cwd(), "public", "media", "projects");

function list(dir: string, ext: RegExp) {
  try {
    return fs.readdirSync(dir).filter((f) => ext.test(f)).sort();
  } catch {
    return [];
  }
}

// cache-busting version from the file's size, so re-captured media refreshes. Not the mtime: on Vercel the
// files carry one date at build time and another in the functions, so every page re-render after a content
// edit gave every picture a new URL (all images flashed, re-optimised and downloaded again).
function versioned(dir: string, rel: string, f: string) {
  let v = 0;
  try {
    v = fs.statSync(path.join(dir, f)).size;
  } catch {}
  return `/media/projects/${rel}/${f}?v=${v.toString(36)}`;
}

/**
 * Media for a project, generated by the capture scripts into public/media/projects/<slug>:
 * - shots/  d* = desktop sections, s* = sub-pages, e* = extra (admin…), m* = mobile
 * - clips/  short "how it works" loops cut from the scroll recording
 * - logo-(light|dark|box).png — the site's own logo (scripts/logo_tone.py), shown on the case hero
 * - shots/<locale>/d01|m01 — the first screens in another language, for sites that have one
 * plus any images uploaded in the admin (media.gallery → "extra").
 */
export function getShots(p: Project, locale?: string): Shots {
  const dir = path.join(ROOT, p.slug, "shots");
  const files = list(dir, /\.webp$/);
  const url = (f: string) => versioned(dir, `${p.slug}/shots`, f);
  const clipDir = path.join(ROOT, p.slug, "clips");
  const clips = list(clipDir, /\.mp4$/).map((f) => versioned(clipDir, `${p.slug}/clips`, f));
  const logoFile = list(path.join(ROOT, p.slug), /^logo-(light|dark|box)\.(png|svg|webp)$/)[0];
  const desktop = files.filter((f) => f.startsWith("d")).map(url);
  const mobile = files.filter((f) => f.startsWith("m")).map(url);
  // a site that exists in several languages: its first screens in the visitor's language (scripts/lang-shots.mjs)
  if (locale) {
    const ldir = path.join(dir, locale);
    const lfiles = list(ldir, /^(d|m)01\.webp$/);
    const lurl = (f: string) => versioned(ldir, `${p.slug}/shots/${locale}`, f);
    if (lfiles.includes("d01.webp") && desktop.length) desktop[0] = lurl("d01.webp");
    if (lfiles.includes("m01.webp") && mobile.length) mobile[0] = lurl("m01.webp");
  }
  return {
    desktop,
    mobile,
    pages: files.filter((f) => f.startsWith("s")).map(url),
    extra: [...files.filter((f) => f.startsWith("e")).map(url), ...(p.media.gallery ?? [])],
    clips,
    logo: logoFile ? { src: versioned(path.join(ROOT, p.slug), p.slug, logoFile), tone: logoFile.split(/[-.]/)[1] as "light" | "dark" | "box" } : null,
  };
}
